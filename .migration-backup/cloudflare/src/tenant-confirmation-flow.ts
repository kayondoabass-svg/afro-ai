import { parseTenantOrigins, validTenantOrigin } from "../../shared/tenant-origins";

const now = () => Math.floor(Date.now()/1000);
const random = () => crypto.randomUUID()+crypto.randomUUID();
const encode = (bytes: Uint8Array) => btoa(String.fromCharCode(...bytes)).replace(/\+/g,"-").replace(/\//g,"_").replace(/=+$/,"");
const digest = async (value:string) => new Uint8Array(await crypto.subtle.digest("SHA-256",new TextEncoder().encode(value)));
const hex = async (value:string) => [...await digest(value)].map(b=>b.toString(16).padStart(2,"0")).join("");
const parse = (raw:string|null) => {try{return JSON.parse(raw||"{}");}catch{return {};}};
type Dependencies = {
  authenticate:(c:any)=>Promise<any>;
  ownedTenant:(c:any,id:string)=>Promise<any>;
  issue:(c:any,tenantId:string,userId:string)=>Promise<string>;
  verify:(c:any,token:string)=>Promise<any>;
  checkPassword:(password:string,hash:string)=>Promise<boolean>;
  mail:(c:any,t:any,user:any,purpose:"verify",context?:any)=>Promise<any>;
  limited:(c:any,t:any,action:string,email?:string)=>Promise<boolean>;
};

export function tenantConfirmationFlow(deps:Dependencies) {
  async function validCallback(c:any,t:any,value:unknown) {
    if(typeof value!=="string" || value.length>2048)return false;
    try {
      const url=new URL(value);
      if(url.search || url.hash || url.username || url.password || !validTenantOrigin(url.origin) ||
        !parseTenantOrigins(t.allowed_origins).includes(url.origin))return false;
      if(url.protocol==="http:")return ["localhost","127.0.0.1"].includes(url.hostname);
      const domains=await c.env.DB.prepare("SELECT domain FROM tenant_domains WHERE tenant_id=? AND verified_at IS NOT NULL").bind(t.id).all();
      return domains.results.some((d:any)=>url.hostname===d.domain || url.hostname.endsWith(`.${d.domain}`));
    }catch{return false;}
  }
  async function configured(c:any,t:any) {
    const config=await c.env.DB.prepare("SELECT callback_url FROM tenant_confirmation_config WHERE tenant_id=?").bind(t.id).first();
    return config?.callback_url && await validCallback(c,t,config.callback_url) ? config.callback_url : null;
  }
  async function prepare(c:any,t:any,body:any) {
    if(body.confirmation===undefined)return null; // Non-breaking legacy signup.
    const owner=await deps.authenticate(c);
    if(owner?.id!==t.id)return c.json({message:"Use this project's private API key from your backend."},401);
    const callback=await configured(c,t);
    if(!callback)return c.json({message:"Configure a verified backend confirmation callback in project Setup first."},409);
    const input=body.confirmation;
    if(!input || !/^[A-Za-z0-9_-]{32,128}$/.test(input.state||"") ||
      !/^[A-Za-z0-9_-]{43}$/.test(input.code_challenge||"") || input.code_challenge_method!=="S256")
      return c.json({message:"Provide a random state and an S256 PKCE challenge generated by your backend."},400);
    return {callback,state:input.state,challenge:input.code_challenge};
  }
  async function start(c:any,t:any,userId:string,context:any) {
    if(!context)return undefined;
    const pending=random(),hash=await hex(pending),ts=now();
    await c.env.DB.batch([
      c.env.DB.prepare("UPDATE tenant_auth_tokens SET used_at=? WHERE tenant_id=? AND user_id=? AND purpose='confirmation_pending' AND used_at IS NULL").bind(ts,t.id,userId),
      c.env.DB.prepare("INSERT INTO tenant_auth_tokens(hash,tenant_id,user_id,purpose,expires_at,context,created_at) VALUES(?,?,?,'confirmation_pending',?,?,?)")
        .bind(hash,t.id,userId,ts+86400,JSON.stringify(context),ts),
    ]);
    // This opaque pending ID is deliberately NOT a login token.
    return {pendingId:pending,mailContext:{confirmation_pending:hash}};
  }
  async function complete(c:any,t:any,verification:any) {
    const pendingHash=parse(verification.context).confirmation_pending;
    if(typeof pendingHash!=="string")return null;
    const pending=await c.env.DB.prepare("SELECT * FROM tenant_auth_tokens WHERE hash=? AND tenant_id=? AND user_id=? AND purpose='confirmation_pending' AND used_at IS NULL AND expires_at>?")
      .bind(pendingHash,t.id,verification.user_id,now()).first();
    if(!pending)return null;
    const context=parse(pending.context);
    const current=await configured(c,t);
    if(!current || current!==context.callback) {
      await c.env.DB.prepare("UPDATE tenant_auth_tokens SET used_at=? WHERE hash=? AND tenant_id=? AND used_at IS NULL").bind(now(),pendingHash,t.id).run();
      return null;
    }
    const code=random(),codeHash=await hex(code),ts=now();
    const result=await c.env.DB.batch([
      c.env.DB.prepare(`INSERT INTO tenant_auth_tokens(hash,tenant_id,user_id,purpose,expires_at,context,created_at)
        SELECT ?,?,?,'confirmation_code',?,?,? WHERE EXISTS
        (SELECT 1 FROM tenant_auth_tokens WHERE hash=? AND tenant_id=? AND used_at IS NULL AND expires_at>?)`)
        .bind(codeHash,t.id,verification.user_id,ts+120,JSON.stringify({...context,pendingHash}),ts,pendingHash,t.id,ts),
      c.env.DB.prepare("UPDATE tenant_auth_tokens SET used_at=? WHERE hash=? AND tenant_id=? AND used_at IS NULL").bind(ts,pendingHash,t.id),
    ]);
    if(!result[0].meta.changes)return null;
    const destination=new URL(current);
    destination.searchParams.set("code",code);
    destination.searchParams.set("state",context.state);
    c.header("Cache-Control","no-store");
    c.header("Referrer-Policy","no-referrer");
    return destination.toString();
  }
  function register(app:any) {
    const configPath="/v1/admin/tenants/:id/confirmation-flow";
    app.get(configPath,async(c:any)=>{
      const t=await deps.ownedTenant(c,c.req.param("id"));if(t instanceof Response)return t;
      const row=await c.env.DB.prepare("SELECT callback_url FROM tenant_confirmation_config WHERE tenant_id=?").bind(t.id).first();
      return c.json({enabled:!!await configured(c,t),callbackUrl:row?.callback_url||null,
        exchangeUrl:new URL(`/cf-auth/v1/t/${encodeURIComponent(t.slug)}/confirmation/exchange`,c.env.APP_URL).toString()});
    });
    app.patch(configPath,async(c:any)=>{
      const t=await deps.ownedTenant(c,c.req.param("id"));if(t instanceof Response)return t;
      const body=await c.req.json().catch(()=>({}));
      if(body.callbackUrl!==null && !await validCallback(c,t,body.callbackUrl))
        return c.json({message:"Use an exact HTTPS backend callback URL on a verified, allowed project origin, without a query string or fragment. HTTP localhost is allowed for development."},400);
      await c.env.DB.prepare(`INSERT INTO tenant_confirmation_config(tenant_id,callback_url,updated_at) VALUES(?,?,?)
        ON CONFLICT(tenant_id) DO UPDATE SET callback_url=excluded.callback_url,updated_at=excluded.updated_at`)
        .bind(t.id,body.callbackUrl,now()).run();
      return c.json({enabled:!!body.callbackUrl,callbackUrl:body.callbackUrl,
        exchangeUrl:new URL(`/cf-auth/v1/t/${encodeURIComponent(t.slug)}/confirmation/exchange`,c.env.APP_URL).toString()});
    });
    app.post("/t/:slug/confirmation/restart",async(c:any)=>{
      const t=await deps.authenticate(c);
      if(!t || t.slug!==c.req.param("slug"))return c.json({message:"Unauthorized."},401);
      const body=await c.req.json().catch(()=>({}));
      if(await deps.limited(c,t,"confirmation-restart:"+await hex(String(body.email||"").toLowerCase())))return c.json({message:"Too many attempts. Please wait."},429);
      const prepared=await prepare(c,t,body);if(prepared instanceof Response)return prepared;
      if(!prepared)return c.json({message:"Backend confirmation parameters are required."},400);
      const user=await c.env.DB.prepare("SELECT id,email,email_verified,password_hash FROM users WHERE tenant_id=? AND email=?")
        .bind(t.id,String(body.email||"").trim().toLowerCase()).first();
      if(!user || !user.password_hash || !await deps.checkPassword(String(body.password||""),user.password_hash))
        return c.json({message:"Wrong email or password."},401);
      if(user.email_verified)return c.json({message:"Email is already confirmed. Use normal login.",code:"ALREADY_CONFIRMED"},409);
      const recent=await c.env.DB.prepare("SELECT created_at FROM tenant_auth_tokens WHERE tenant_id=? AND user_id=? AND purpose='verify' AND created_at>? ORDER BY created_at DESC LIMIT 1")
        .bind(t.id,user.id,now()-60).first();
      if(recent){
        c.header("Retry-After",String(Math.max(1,60-now()+recent.created_at)));
        return c.json({message:"A confirmation was just sent. Wait one minute before restarting signup."},429);
      }
      const pending=await start(c,t,user.id,prepared);
      try{await deps.mail(c,t,user,"verify",pending?.mailContext);}catch{return c.json({message:"Verification delivery is unavailable. Retry after one minute."},503);}
      return c.json({verificationRequired:true,pendingId:pending?.pendingId});
    });
    app.post("/t/:slug/confirmation/exchange",async(c:any)=>{
      const t=await deps.authenticate(c);
      if(!t || t.slug!==c.req.param("slug"))return c.json({message:"Unauthorized."},401);
      const body=await c.req.json().catch(()=>({}));
      if(typeof body.code!=="string" || body.code.length>256 || !/^[A-Za-z0-9._~-]{43,128}$/.test(body.code_verifier||""))
        return c.json({message:"Invalid or expired confirmation exchange."},400);
      if(await deps.limited(c,t,"confirmation-exchange:"+await hex(body.code)))return c.json({message:"Too many attempts. Please wait."},429);
      const row=await c.env.DB.prepare("SELECT * FROM tenant_auth_tokens WHERE hash=? AND tenant_id=? AND purpose='confirmation_code' AND used_at IS NULL AND expires_at>?")
        .bind(await hex(body.code),t.id,now()).first();
      const context=parse(row?.context);
      if(!row || context.state!==body.state || context.callback!==body.redirect_uri ||
        context.callback!==await configured(c,t) || encode(await digest(body.code_verifier))!==context.challenge)
        return c.json({message:"Invalid or expired confirmation exchange."},400);
      const old=body.previous_token ? await deps.verify(c,String(body.previous_token)) : null;
      if(body.previous_token && (!old || old.tenantId!==t.id || old.userId!==row.user_id))
        return c.json({message:"The previous session does not belong to this confirmation."},400);
      const ts=now();
      const claim=c.env.DB.prepare(`UPDATE tenant_auth_tokens SET used_at=? WHERE hash=? AND tenant_id=? AND used_at IS NULL AND expires_at>?
        AND EXISTS(SELECT 1 FROM users WHERE id=? AND tenant_id=? AND email_verified=1)`).bind(ts,row.hash,t.id,ts,row.user_id,t.id);
      const statements:any[]=[];
      if(old)statements.push(c.env.DB.prepare(`UPDATE tenant_sessions SET revoked_at=? WHERE id=? AND tenant_id=? AND user_id=?
        AND EXISTS(SELECT 1 FROM tenant_auth_tokens WHERE hash=? AND tenant_id=? AND used_at IS NULL AND expires_at>?)`)
        .bind(ts,old.sessionId,t.id,row.user_id,row.hash,t.id,ts));
      statements.push(claim);
      const result=await c.env.DB.batch(statements);
      if(!result.at(-1).meta.changes)return c.json({message:"Confirmation exchange already used or expired."},400);
      const token=await deps.issue(c,t.id,row.user_id);
      return c.json({token,tokenType:"Bearer",expiresIn:86400,pendingExpired:true});
    });
  }
  return {prepare,start,complete,register};
}
