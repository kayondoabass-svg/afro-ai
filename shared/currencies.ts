export function getCountryByIsoCode(isoCode: string): AfricanCountry | undefined {
  return africanCountries.find((c) => c.isoCode === isoCode.toUpperCase());
}

export function getCountryByName(name: string): AfricanCountry | undefined {
  return africanCountries.find((c) => c.name.toLowerCase() === name.toLowerCase());
}

export function getCurrencyForCountry(isoCode: string): { code: string; symbol: string; rate: number } | undefined {
  const country = getCountryByIsoCode(isoCode);
  if (!country) return undefined;
  return { code: country.currencyCode, symbol: country.currencySymbol, rate: country.usdExchangeRate };
}

export function convertUsdToLocal(usdAmount: number, isoCode: string): number {
  const country = getCountryByIsoCode(isoCode);
  if (!country) return usdAmount;
  return Math.round(usdAmount * country.usdExchangeRate * 100) / 100;
}

export function formatLocalPrice(usdAmount: number, isoCode: string): string {
  const country = getCountryByIsoCode(isoCode);
  if (!country) return `$${usdAmount.toFixed(2)}`;
  const localAmount = convertUsdToLocal(usdAmount, isoCode);
  if (localAmount >= 1000) {
    return `${country.currencySymbol} ${localAmount.toLocaleString("en", { maximumFractionDigits: 0 })}`;
  }
  return `${country.currencySymbol} ${localAmount.toFixed(2)}`;
}

export function formatUsdPrice(amount: number): string {
  return `$${amount.toFixed(2)}`;
}
